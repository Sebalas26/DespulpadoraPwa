import { Component, computed, inject, signal } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { StateService } from '../../core/services/state.service';
import { NotificationService } from '../../core/services/notification.service';
import { ClientDto, OrderDto, OrderItemDto } from '../../core/models/business.models';

/**
 * Summary statistics for a selected client's purchase history.
 */
export interface ClientHistoryStats {
  orders: OrderDto[];
  recentOrders: OrderDto[];
  totalPurchases: number;
  totalSpent: number;
  totalUnits: number;
  totalKg: number;
  lastPurchaseDate: string;
}

/**
 * Commercial Clients Directory and Sales History management component.
 */
@Component({
  selector: 'app-accounting',
  standalone: true,
  imports: [CommonModule, FormsModule],
  templateUrl: './accounting.component.html',
  styleUrls: ['./accounting.component.scss']
})
export class AccountingComponent {
  readonly stateService = inject(StateService);
  readonly notification = inject(NotificationService);

  readonly showClientForm = signal<boolean>(false);
  readonly selectedHistoryClient = signal<ClientDto | null>(null);

  readonly editingClientId = signal<number | null>(null);
  readonly fullName = signal<string>('');
  readonly identificationNumber = signal<string>('');
  readonly phone = signal<string>('');
  readonly email = signal<string>('');
  readonly address = signal<string>('');
  readonly city = signal<string>('');
  readonly notes = signal<string>('');

  readonly searchQuery = signal<string>('');
  readonly isLoading = computed<boolean>(() => {
    try {
      return typeof this.stateService.isLoading === 'function' ? this.stateService.isLoading() : false;
    } catch {
      return false;
    }
  });

  /**
   * Synchronizes operational state when entering the clients and billing module.
   */
  constructor() {
    try {
      this.stateService.refreshAll?.();
    } catch {
      return;
    }
  }

  readonly filteredClients = computed<ClientDto[]>(() => {
    try {
      const q = this.searchQuery().trim().toLowerCase();
      const list = this.stateService.clients();
      if (!q) {
        return list;
      }
      return list.filter((c: ClientDto) => {
        const hay = `${c.fullName} ${c.identificationNumber} ${c.phone} ${c.email || ''} ${c.address || ''} ${c.city || ''}`.toLowerCase();
        return hay.includes(q);
      });
    } catch {
      return [];
    }
  });

  /**
   * Retrieves all non-cancelled orders associated with a specific client.
   */
  getClientOrders(client: ClientDto): OrderDto[] {
    try {
      const nameNorm = client.fullName.trim().toLowerCase();
      const phoneNorm = (client.phone || '').replace(/\s+/g, '');

      return this.stateService
        .orders()
        .filter((o: OrderDto) => {
          if (o.status === 'CANCELLED') {
            return false;
          }
          if (o.clientId === client.clientId) {
            return true;
          }
          if (o.clientName && o.clientName.trim().toLowerCase() === nameNorm) {
            return true;
          }
          if (phoneNorm && o.clientPhone && o.clientPhone.replace(/\s+/g, '') === phoneNorm) {
            return true;
          }
          return false;
        })
        .sort((a: OrderDto, b: OrderDto) =>
          (b.orderDate || b.createdAt).localeCompare(a.orderDate || a.createdAt)
        );
    } catch {
      return [];
    }
  }

  /**
   * Returns the total number of non-cancelled orders placed by a client.
   */
  getClientPurchaseCount(client: ClientDto): number {
    try {
      return this.getClientOrders(client).length;
    } catch {
      return 0;
    }
  }

  /**
   * Calculates the cumulative revenue generated by a client across all valid orders.
   */
  getClientTotalSpent(client: ClientDto): number {
    try {
      return this.getClientOrders(client).reduce(
        (sum: number, o: OrderDto) => sum + (o.totalAmount || 0),
        0
      );
    } catch {
      return 0;
    }
  }

  readonly selectedClientHistoryStats = computed<ClientHistoryStats>(() => {
    try {
      const client = this.selectedHistoryClient();
      if (!client) {
        return {
          orders: [],
          recentOrders: [],
          totalPurchases: 0,
          totalSpent: 0,
          totalUnits: 0,
          totalKg: 0,
          lastPurchaseDate: 'Sin compras'
        };
      }

      const orders = this.getClientOrders(client);
      const totalSpent = orders.reduce((sum: number, o: OrderDto) => sum + (o.totalAmount || 0), 0);
      let totalUnits = 0;
      let totalKg = 0;

      orders.forEach((o: OrderDto) => {
        o.items.forEach((item: OrderItemDto) => {
          const qty = item.quantity || 0;
          const gram = item.grammage || 0;
          totalUnits += qty;
          totalKg += (qty * gram) / 1000;
        });
      });

      const lastDate =
        orders.length > 0
          ? orders[0].orderDate || orders[0].createdAt.substring(0, 10)
          : 'Sin compras registradas';

      return {
        orders,
        recentOrders: orders.slice(0, 6),
        totalPurchases: orders.length,
        totalSpent,
        totalUnits,
        totalKg: Number(totalKg.toFixed(1)),
        lastPurchaseDate: lastDate
      };
    } catch {
      return {
        orders: [],
        recentOrders: [],
        totalPurchases: 0,
        totalSpent: 0,
        totalUnits: 0,
        totalKg: 0,
        lastPurchaseDate: 'Sin compras'
      };
    }
  });

  /**
   * Formats an order's line items into a compact single-line summary.
   */
  formatOrderItemsCompact(order: OrderDto): string {
    try {
      if (!order.items || order.items.length === 0) {
        return 'Sin ítems';
      }
      return order.items
        .map((i: OrderItemDto) => `${i.quantity}x ${i.fruitName} ${i.grammage}g`)
        .join(' · ');
    } catch {
      return 'Sin ítems';
    }
  }

  /**
   * Duplicates a historical order for the given client.
   */
  reorderPurchase(order: OrderDto, client: ClientDto): void {
    try {
      const newOrder = this.stateService.createOrder({
        clientName: client.fullName || order.clientName,
        clientPhone: client.phone || order.clientPhone,
        clientAddress: client.address || order.clientAddress,
        paymentMethodName: order.paymentMethodName || '',
        notes: `Pedido repetido desde histórico (${order.orderNumber})`,
        items: order.items.map((i: OrderItemDto) => ({
          fruitName: i.fruitName || '',
          grammage: (i.grammage || 0) as 140 | 250 | 500 | 1000,
          quantity: i.quantity,
          unitPrice: i.unitPrice
        }))
      });

      this.stateService.orders.update((list: OrderDto[]) =>
        list.map((o: OrderDto) =>
          o.orderId === newOrder.orderId ? { ...o, clientId: client.clientId } : o
        )
      );
    } catch {
      return;
    }
  }

  /**
   * Opens the modal to create a new client.
   */
  openCreateClient(): void {
    try {
      this.resetForm();
      this.showClientForm.set(true);
    } catch {
      return;
    }
  }

  /**
   * Closes the client creation/edition modal and resets form fields.
   */
  closeClientForm(): void {
    try {
      this.resetForm();
      this.showClientForm.set(false);
    } catch {
      return;
    }
  }

  /**
   * Opens the sales history modal for the selected client.
   */
  openClientSalesHistory(client: ClientDto): void {
    try {
      this.selectedHistoryClient.set(client);
    } catch {
      return;
    }
  }

  /**
   * Closes the client sales history modal.
   */
  closeClientSalesHistory(): void {
    try {
      this.selectedHistoryClient.set(null);
    } catch {
      return;
    }
  }

  /**
   * Validates and saves a new or edited commercial client.
   */
  saveClient(): void {
    try {
      const name = this.fullName().trim();
      const idNum = this.identificationNumber().trim();
      const ph = this.phone().trim();

      if (!name) {
        this.notification.warning('Nombre requerido', 'Ingresa el nombre o razón social del cliente.');
        return;
      }
      if (!ph) {
        this.notification.warning('Teléfono requerido', 'Ingresa el número de contacto o WhatsApp del cliente.');
        return;
      }

      const editId = this.editingClientId();
      if (editId !== null) {
        this.stateService.updateClient(editId, {
          fullName: name,
          identificationNumber: idNum,
          phone: ph,
          email: this.email().trim(),
          address: this.address().trim(),
          city: this.city().trim(),
          notes: this.notes().trim()
        });
      } else {
        this.stateService.createClient({
          fullName: name,
          identificationNumber: idNum,
          phone: ph,
          email: this.email().trim(),
          address: this.address().trim(),
          city: this.city().trim(),
          notes: this.notes().trim()
        });
      }

      this.closeClientForm();
    } catch {
      return;
    }
  }

  /**
   * Populates the form with an existing client's details and opens the modal.
   */
  editClient(client: ClientDto): void {
    try {
      this.editingClientId.set(client.clientId);
      this.fullName.set(client.fullName);
      this.identificationNumber.set(client.identificationNumber);
      this.phone.set(client.phone);
      this.email.set(client.email || '');
      this.address.set(client.address || '');
      this.city.set(client.city || '');
      this.notes.set(client.notes || '');
      this.showClientForm.set(true);
    } catch {
      return;
    }
  }

  /**
   * Deletes a client by identifier and closes any open modals for that client.
   */
  deleteClient(clientId: number): void {
    try {
      this.stateService.deleteClient(clientId);
      if (this.editingClientId() === clientId) {
        this.closeClientForm();
      }
      if (this.selectedHistoryClient()?.clientId === clientId) {
        this.closeClientSalesHistory();
      }
    } catch {
      return;
    }
  }

  /**
   * Resets all client form signals to empty defaults.
   */
  resetForm(): void {
    try {
      this.editingClientId.set(null);
      this.fullName.set('');
      this.identificationNumber.set('');
      this.phone.set('');
      this.email.set('');
      this.address.set('');
      this.city.set('');
      this.notes.set('');
    } catch {
      return;
    }
  }

  /**
   * Maps an order status code to its Spanish display label.
   */
  getOrderStatusLabel(status: string): string {
    try {
      switch (status) {
        case 'DELIVERED':
          return 'Entregado';
        case 'DISPATCHED':
          return 'En ruta';
        case 'BILLED':
          return 'Facturado';
        case 'PICKING':
          return 'En alistamiento';
        default:
          return 'Pendiente';
      }
    } catch {
      return 'Pendiente';
    }
  }

  /**
   * Formats a numeric value as Colombian Pesos (COP).
   */
  formatCOP(val: number): string {
    try {
      return new Intl.NumberFormat('es-CO', {
        style: 'currency',
        currency: 'COP',
        maximumFractionDigits: 0
      }).format(val || 0);
    } catch {
      return '$0';
    }
  }
}
